"""Write the manuscript tables that are computed rather than copied from one JSON field: body Table 1 (tab31, student means
per interval), body Table 2 (tab32, pair means of the edit effects), appendix Table 9 (tab22, intervals with student-mean
coverage changes) and appendix Table 15 (tab19 / tab19b, cell value +- SD over seeds).
Usage: MANUSCRIPT_DIR=<manuscript checkout> python experiments/lambda_lora_bits/paper_tables.py
(writes <MANUSCRIPT_DIR>/tables/; an explicit output directory may be given as the first argument).
The other tables copy JSON fields directly; experiments/manuscript_audit/t_tables.py checks every table."""
import json, math, os, statistics as st, sys

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
EXP = os.environ.get('RESULTS_DIR', os.path.join(REPO_ROOT, 'experiments'))
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.environ.get('MANUSCRIPT_DIR', os.path.join(os.path.dirname(REPO_ROOT), 'NAACL_cot_distill_lora_subspace')), 'tables')
J = lambda f: json.load(open(os.path.join(EXP, f)))
S = ['Qwen', 'Llama', 'OLMo']
P = 'ABC'
CELLS = [f'{p}/{s}' for p in P for s in S]
lc, bl, rv, ss, me, em, es, pb = (J(f) for f in ['length_confound.json', 'baselines.json', 'review_stats.json',
                                                  'seed_spread.json', 'main_edits.json', 'energy_match.json',
                                                  'edit_stats.json', 'paired_bootstrap.json'])


def num(x, d):
    s = f'{x:,.{d}f}'
    return s.replace('-', '$-$') if s.startswith('-') else s


def pm(seeds, d):
    return f'{num(st.mean(seeds), d)} $\\pm$ {st.stdev(seeds):.{d}f}'


def write(name, lines):
    with open(os.path.join(OUT, name), 'w') as f:
        f.write('\n'.join(lines) + '\n')


# ---------------- Table 1 (tab31): one row per interval, students averaged ----------------
t1 = ['% Body table (label tab:lenbody), generated by experiments/lambda_lora_bits/paper_tables.py from experiments/length_confound.json pairs.<P>.intervals[]:',
      '% log_len_drop, think and markers at both ends (change and end/start ratio), kept_vs_half_reference averaged over the three students,',
      '% loss = mean over students of -ln(kept)/log_len_drop. Held and switch intervals of every pair and pair B\'s 0.6->0.8 after interval.',
      '\\begin{tabular}{lllrrrrr}', '\\toprule',
      'Pair & $\\lambda$ & Class & $\\Delta\\log L$ & $\\Delta$Think & Markers & Kept & Loss \\\\',
      ' & & & & (pp) & ($\\times$) & & \\\\', '\\midrule']
cls = {'held': 'held', 'switch': 'switch', 'after': 'after'}
for i, p in enumerate(P):
    if i:
        t1.append('\\midrule')
    for iv in lc['pairs'][p]['intervals']:
        if iv['class'] == 'after' and not (p == 'B' and iv['interval'] == '0.6->0.8'):
            continue
        a, b = (x if x != '0.0' else '0' for x in iv['interval'].split('->'))
        k = [iv['kept_vs_half_reference'][s] for s in S]
        loss = [-math.log(x) / iv['log_len_drop'] for x in k]
        dth = iv['think'][1] - iv['think'][0]
        lam = f'{a}--{b} & {iv["class"].capitalize()}'
        t1.append(f'{p} & {lam} & {num(iv["log_len_drop"], 2)} & {"+" if round(dth) > 0 else ""}{num(dth, 0) if round(dth) else "0"} & '
                  f'{iv["markers"][1] / iv["markers"][0]:.2f} & {st.mean(k):.2f} & {st.mean(loss):.2f} \\\\')
t1 += ['\\bottomrule', '\\end{tabular}']
write('tab31.tex', t1)

